const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
const web = path.join(process.cwd(), 'Resources/OuterShellWeb');
const source = fs.readFileSync(path.join(web, 'app.js'), 'utf8');
const unix = fs.readFileSync(path.join(web, 'opencode-start.sh'), 'utf8');
const windows = fs.readFileSync(path.join(web, 'opencode-start.ps1'), 'utf8');
const names = [...new Set([...`${unix}${windows}`.matchAll(/__OPENCODE_SHA256_([\w.-]+)__/g)].map(m => m[1]))];
const release = {tag_name:'v1.99.2', assets:names.map(name=>({name,digest:'sha256:'+'a'.repeat(64)}))};
let pages = [], calls = 0;
const context = {AbortSignal, fetch:async()=>{calls++;return {ok:true,json:async()=>pages.shift()}}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  const openCodeUpdates ='),source.indexOf('  async function openOpenCodeUpdate(')),context);
(async()=>{
  pages = [[{tag_name:'v2.2.2'}, {...release,prerelease:true}, {...release,draft:true}, {tag_name:'process-daemon-v9.0.0'}, {...release,tag_name:'v1.99.1'},release]];
  assert.equal((await context.resolveOpenCodeRelease()).tag_name,release.tag_name);
  pages = [Array.from({length:30},()=>({tag_name:'v2.0.0'})),[release]];
  calls=0; await context.resolveOpenCodeRelease(); assert.equal(calls,2);
  pages=[[]]; await assert.rejects(context.resolveOpenCodeRelease(),/Could not find/);
  context.fetch=async()=>({ok:false,status:403});
  await assert.rejects(context.resolveOpenCodeRelease(),/HTTP 403/);
  assert.throws(()=>context.prepareOpenCodeRelease(unix,{...release,tag_name:'v2.0.0'}),/Unsupported/);
  assert.throws(()=>context.prepareOpenCodeRelease(unix,{...release,assets:[]}),/verified download/);
  assert.throws(()=>context.openCodeUpdateCommand('bad',release,false),/Invalid/);
  const ps = context.openCodeUpdateCommand(windows,release,true);
  assert(ps.startsWith('& {')); assert(!ps.includes('__')); assert(!ps.includes('Start-Process'));
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(),'opencode-update-test-'));
  try {
    const bin=path.join(scratch,'mock-bin');fs.mkdirSync(bin);
    const stage=path.join(scratch,'archive');fs.mkdirSync(stage);
    fs.writeFileSync(path.join(stage,'opencode'),'#!/bin/sh\necho 1.99.2\n',{mode:0o755});
    execFileSync('zip',['-q',path.join(scratch,'download.zip'),'opencode'],{cwd:stage});
    const digest=crypto.createHash('sha256').update(fs.readFileSync(path.join(scratch,'download.zip'))).digest('hex');
    const binary=path.join(scratch,'.local/share/outershell-opencode/1.19.3/opencode');
    fs.mkdirSync(path.dirname(binary),{recursive:true});fs.writeFileSync(binary,'original',{mode:0o755});
    fs.writeFileSync(path.join(bin,'uname'),'#!/bin/sh\ncase "$1" in -s) echo Darwin;; -m) echo arm64;; esac\n',{mode:0o755});
    fs.writeFileSync(path.join(bin,'curl'),'#!/bin/sh\nwhile [ "$1" != -o ]; do shift; done\ncp "$HOME/download.zip" "$2"\n',{mode:0o755});
    const verified={...release,assets:names.map(name=>({name,digest:'sha256:'+digest}))};
    const run = metadata => {
      const command=context.openCodeUpdateCommand(unix,metadata,false);
      assert(!command.includes('__')); assert(!command.includes(' serve '));
      execFileSync('sh',['-n'],{input:command});
      return execFileSync('sh',[],{input:command,env:{...process.env,HOME:scratch,PATH:bin+':/usr/bin:/bin'},stdio:['pipe','pipe','pipe']});
    };
    assert.throws(()=>run(release),/checksum verification failed/);
    assert.equal(fs.readFileSync(binary,'utf8'),'original');
    run(verified);
    assert.match(fs.readFileSync(binary,'utf8'),/echo 1.99.2/);
    const second=path.join(scratch,'.local/share/outershell-opencode/other');fs.mkdirSync(second);fs.writeFileSync(path.join(second,'opencode'),'original',{mode:0o755});
    assert.throws(()=>run(verified),/Multiple OpenCode installations/);
  } finally {fs.rmSync(scratch,{recursive:true,force:true});}
  console.log('PASS: stable compatible release selection, pagination, lookup failures, digest validation, update generation and binary replacement');
})().catch(error=>{console.error(error);process.exitCode=1});
