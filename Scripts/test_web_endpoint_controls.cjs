const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../Resources/OuterShellWeb/app.js'), 'utf8');
let closes = 0, errors = [], finish;
const state = { endpointControls: new Map() };
const context = { state, closeDialog: () => { closes++; }, renderSafeSpaces() {}, toast: error => errors.push(error) };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  async function performEndpointControl('), source.indexOf('  async function performControl(')), context);
(async () => {
  const pending = context.performEndpointControl('one', 'stopApp', () => new Promise(resolve => { finish = resolve; }));
  assert.equal(closes, 1);
  assert.equal(state.endpointControls.get('one'), 'Stopping');
  await context.performEndpointControl('one', 'stopApp', () => { throw Error('duplicate'); });
  assert.equal(closes, 1);
  let otherRan = false;
  await context.performEndpointControl('two', 'startApp', async () => { otherRan = true; });
  assert.equal(otherRan, true);
  assert.equal(state.endpointControls.get('one'), 'Stopping');
  assert.equal(state.endpointControls.has('two'), false);
  const closeCount = closes;
  finish(); await pending;
  assert.equal(closes, closeCount, 'Completion must not close a subsequently opened menu');
  assert.equal(state.endpointControls.size, 0);
  await context.performEndpointControl('failed', 'stopApp', async () => { throw Error('Could not stop'); });
  assert.deepEqual(errors, ['Could not stop']);
  assert.equal(state.endpointControls.size, 0);
  console.log('PASS: immediate dismissal, independent controls, duplicate prevention, failure cleanup, and no late menu dismissal');
})().catch(error => { console.error(error); process.exitCode = 1; });
