const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const web = 'Resources/OuterShellWeb';
const source = fs.readFileSync(web + '/app.js', 'utf8');
const context = {openCodeContainerFragment: async () => 'RUN install-opencode'};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  const containerAppCatalog'), source.indexOf('  async function openCodeContainerFragment')), context);
(async () => {
  for (const [id, name] of [['files','Files'],['plaintext','Plaintext'],['top','Top']]) {
    const original = 'FROM ubuntu:24.04\nRUN echo custom\n';
    const draft = await context.containerAppDraft(original, id);
    assert(draft.dockerfile.startsWith(original));
    assert.match(draft.message, /added to this draft/);
    assert(draft.dockerfile.includes(name + '/${platform}.tar.gz'));
    assert(draft.dockerfile.includes(`Name=${name}`));
    assert(draft.dockerfile.includes(`org.outershell.${name}:main`));
    assert.match(draft.dockerfile, /linux-aarch64/); assert.match(draft.dockerfile, /linux-x86_64/);
    assert(!/__APP_NAME__|__SERVICE_ID__|__OPENER__/.test(draft.dockerfile));
    assert.equal(draft.dockerfile.includes('opener upsert'), id === 'plaintext');
    const again = await context.containerAppDraft(draft.dockerfile,id);
    assert.equal(again.dockerfile,draft.dockerfile);
    assert.match(again.message,/already includes/);
    const oci = `FROM ubuntu:24.04\nCOPY --from=ghcr.io/outergroup/outershell-app-${id}:4 /outershell-rootfs/ /`;
    assert.equal((await context.containerAppDraft(oci,id)).dockerfile,oci);
  }
  assert.match((await context.containerAppDraft('FROM ubuntu:24.04','opencode')).dockerfile,/install-opencode/);
  context.openCodeContainerFragment = async () => { throw Error('Could not load OpenCode'); };
  await assert.rejects(context.containerAppDraft('FROM ubuntu:24.04','opencode'), /Could not load/);
  await assert.rejects(context.containerAppDraft('FROM ubuntu:24.04','unknown'), /Unknown/);
  context.state = {addTab: 'catalog', containerCatalog: {id:'c', original:'FROM ubuntu:24.04', dockerfile:'FROM ubuntu:24.04', selected:[], busy:false}};
  context.openAddDialog = () => {};
  context.escapeHTML = String;
  const calls = [];
  let saved = 'FROM ubuntu:24.04';
  context.safeSpaceRequest = async () => ({workspaces:[{id:'c',recipe:{containerfile:saved}}]});
  context.containerOperation = async (op, values) => { calls.push(op); if (op === 'updateDockerfile') saved = values.dockerfile; };
  context.closeDialog = () => {calls.push('close'); context.state.containerCatalog = null;};
  context.refreshSafeSpaces = async () => {};
  await context.toggleContainerCatalogApp('files');
  await context.toggleContainerCatalogApp('top');
  assert.equal(context.state.containerCatalog.selected.length,2);
  assert.match(context.state.containerCatalog.dockerfile,/org.outershell.Files/);
  assert.match(context.state.containerCatalog.dockerfile,/org.outershell.Top/);
  assert.equal(calls.length,0);
  await context.toggleContainerCatalogApp('files');
  assert.doesNotMatch(context.state.containerCatalog.dockerfile,/org.outershell.Files/);
  await context.saveContainerCatalog();
  assert.deepEqual(calls,['updateDockerfile','rebuildRecipe','close']);
  context.state.containerCatalog = {id:'c',original:saved,dockerfile:saved,selected:[],busy:false};
  assert.match(context.containerCatalogHTML({id:'c'}),/In Dockerfile/);
  for (const name of ['Files', 'Plaintext', 'Top']) assert(context.containerCatalogHTML({id:'c'}).includes(`/web/icons/org.outershell.${name}.png`));
  assert(context.containerCatalogHTML({id:'c'}).includes('/web/icons/opencode.svg'));
  const commented = '# org.outershell.Files\nFROM ubuntu:24.04';
  assert.match((await context.containerAppDraft(commented,'files')).message,/added to this draft/);
  await context.toggleContainerCatalogApp('files');
  saved += '\nRUN echo concurrent-change';
  calls.length = 0;
  await context.saveContainerCatalog();
  assert.equal(calls.length,0);
  assert.match(context.state.containerCatalog.message,/changed elsewhere/);
  console.log('PASS: shared app fragments, registration and opener, architecture selection, draft preservation, duplicate detection, OpenCode delegation, failure handling');
})().catch(error => {console.error(error);process.exitCode=1;});
