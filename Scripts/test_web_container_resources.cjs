const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname, '../Resources/OuterShellWeb/app.js'),'utf8');
const code=source.slice(source.indexOf('  const minimumContainerMemoryInMB'),source.indexOf('  function runtimeOptions('));
const context={};vm.createContext(context);vm.runInContext(code,context);
for(const [text,mb] of [['8',8192],['1.5',1536],['1.5 GB',1536],['512 MB',512],['512m',512],['2g',2048],['  3919 MiB ',3919],['.5',512]])assert.equal(context.parseMemoryMB(text),mb,text);
for(const text of ['','abc','1.5 TB','-1','1e3'])assert(Number.isNaN(context.parseMemoryMB(text)),text);
for(const [mb,text] of [[8192,'8 GB'],[1536,'1.5 GB'],[3919,'3919 MB'],[512,'512 MB'],[128,'128 MB'],[2304,'2.25 GB']])assert.equal(context.formatMemoryMB(mb),text);
const input=()=>({value:'',dataset:{},max:undefined,removeAttribute(name){delete this[name]}});
const newForm=()=>({elements:{cpus:input(),memoryInMB:input()},note:{hidden:true,textContent:''},querySelector(){return this.note}});
const form=newForm();
const docker={name:'Docker',resources:{maxCPUs:2,maxMemoryInMB:3919,defaultCPUs:2,defaultMemoryInMB:3919}};
context.applyContainerResourceLimits(form,docker);
assert.equal(form.elements.cpus.value,'2');assert.equal(form.elements.cpus.max,'2');
assert.equal(form.elements.memoryInMB.value,'3919 MB');
